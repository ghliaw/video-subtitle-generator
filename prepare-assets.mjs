import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdir, mkdtemp, rm, rmdir, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const vendor = new URL('./vendor/', import.meta.url);
const cache = await mkdtemp(join(tmpdir(), 'subtitle-assets-'));
const modelRevision = '5359861c739e955e79d9a303bcbc70fb988958b1';

async function download(url, hash, algorithm, encoding) {
  const response = await fetch(url, { signal: AbortSignal.timeout(180_000) });
  if (!response.ok) throw new Error(`${response.status}: ${url}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  if (createHash(algorithm).update(bytes).digest(encoding) !== hash) {
    throw new Error(`Checksum mismatch: ${url}`);
  }
  return bytes;
}

async function archive(name, version, integrity) {
  const basename = name.split('/').at(-1);
  const url = `https://registry.npmjs.org/${name}/-/${basename}-${version}.tgz`;
  const bytes = await download(url, integrity, 'sha512', 'base64');
  const path = join(cache, `${basename}.tgz`);
  await writeFile(path, bytes);
  return {
    read: (member) => execFileSync('tar', ['-xOf', path, `package/${member}`], {
      maxBuffer: 64 * 1024 * 1024,
    }),
  };
}

async function pack(id, bytes) {
  const chunks = [];
  for (let start = 0; start < bytes.length; start += 384 * 1024) {
    chunks.push(bytes.subarray(start, start + 384 * 1024).toString('base64'));
  }
  await writeFile(new URL(`${id}.js`, vendor),
    `// Generated by prepare-assets.mjs.\nOfflineAssets.receive(${JSON.stringify(id)}, [\n` +
    chunks.map(chunk => `  ${JSON.stringify(chunk)}`).join(',\n') + '\n]);\n');
  console.log(`Packed ${id} (${bytes.length} bytes)`);
}

function classicWhisper(bytes) {
  const modulePlaceholders = ['import.meta.url', 'export default createWhisperNodeModule;'];
  let source = bytes.toString('utf8');
  for (const placeholder of modulePlaceholders) {
    if (!source.includes(placeholder)) throw new Error(`Unexpected Emscripten output: ${placeholder}`);
  }
  // This build runs as a classic Blob worker. The page supplies the WASM bytes.
  source = source.replaceAll('import.meta.url', 'self.location.href')
    .replace(modulePlaceholders[1], '');
  return Buffer.from(source);
}

